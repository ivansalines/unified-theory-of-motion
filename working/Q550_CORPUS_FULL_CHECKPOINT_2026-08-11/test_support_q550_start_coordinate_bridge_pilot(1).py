#!/usr/bin/env python3
"""Validated start-coordinate bridge pilot for the Q=550 frozen-spline cocycle.

This script starts from the rigorously validated m=192 transport balls at dense
center 67 and propagates them across neighboring start-coordinate cells using

    dT/ds = B(s+b) T - T B(s+a),

with (a,b) chosen for line, second, oriented, and 2P_line transports.

The archived dense matrices are used only as a Hermite guide curve.  A rigorous
residual enclosure plus a logarithmic-norm bound transports the certified ball
from cell to cell.  The default run is a local pilot over four cells on each
side; use --cells-each-side 80 only after the pilot margins are satisfactory.

Scope remains the linear cocycle generated by the frozen natural cubic spline.
The nonlinear orbit cache is not yet validated against an exact trajectory.
"""
