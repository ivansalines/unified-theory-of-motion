"""
Q=550 relative-defect micro-box pilot for the frozen-spline cocycle.

This pilot addresses the two failure modes isolated in the previous interval
attempts:

1. A requested microinterval is enclosed with the cubic spline restricted to
   that exact microinterval.  It is never replaced by the box of the complete
   spline segment.

2. Each local transition is validated in a moving frame.  If U(t) is the
   cubic-Hermite approximate local fundamental matrix and

       R = U' - B U,
       X = U (I + E),

   then

       E' = -U^{-1} R (I + E).

   The large rotational part of B therefore disappears from the error-growth
   equation.  On each residual subcell we bound U^{-1} by a Neumann estimate
   around the identity and integrate ||U^{-1}R||.

The script validates one selected dense start only.  Its purpose is to decide
whether this proof architecture produces useful radii before scaling it to all
81 starts.  Scope is still the linear cocycle generated by the frozen natural
cubic spline reconstructed from the archived orbit; the nonlinear orbit cache
is not yet validated against an exact trajectory.
"""

