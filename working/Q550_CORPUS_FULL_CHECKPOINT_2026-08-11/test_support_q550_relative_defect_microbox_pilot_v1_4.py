def load_module(path: Path, name: str) -> ModuleType:
    path = path.resolve()
    if not path.exists():
        raise FileNotFoundError(f"Required script not found: {path}")
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Could not import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def require_attributes(module: ModuleType, names: Iterable[str], label: str) -> None:
    missing = [name for name in names if not hasattr(module, name)]
    if missing:
        raise AttributeError(f"{label} is missing: " + ", ".join(missing))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def outward(value: float) -> float:
    return float(np.nextafter(float(value), np.inf))


def box_spectral_upper(base: ModuleType, box: Any) -> float:
    """Upper bound ||A||_2 <= sqrt(||A||_1 ||A||_inf) for A in box."""
    absolute = np.asarray(base.box_abs_upper(box), dtype=float)
    one = outward(float(np.max(np.sum(absolute, axis=0))))
    infinity = outward(float(np.max(np.sum(absolute, axis=1))))
    with mp.workdps(base.MP_DPS):
        value = mp.sqrt(mp.mpf(one) * mp.mpf(infinity))
        _, high = base.mp_bracket(value, ulps=4)
    return float(high)


def box_width_max(box: Any) -> float:
    return float(np.max(np.asarray(box.hi, dtype=float) - np.asarray(box.lo, dtype=float)))


class LocalCubicGeneratorEnvelope:
    """Outward-rounded generator enclosure on the exact requested interval.

    Unlike the coarse envelope used by the first interval attempt, ``box(a, b)``
    restricts every cubic-spline segment to the actual overlap with ``[a, b]``.
    This preserves the small generator variation on residual microcells.
    """

    def __init__(
        self,
        base: ModuleType,
        audit: ModuleType,
        spline: Any,
        knots: np.ndarray,
        *,
        domain_left: float,
        domain_right: float,
        kappa0: float,
        params: Any,
        basis: np.ndarray,
        basis_box: Any,
        left_matrix: np.ndarray,
        left_box: Any,
    ) -> None:
        self.base = base
        self.audit = audit
        self.spline = spline
        self.knots = np.asarray(knots, dtype=float)
        self.domain_left = float(domain_left)
        self.domain_right = float(domain_right)
        self.kappa0 = float(kappa0)
        self.params = params
        self.basis = np.asarray(basis, dtype=float)
        self.basis_box = basis_box
        self.left_matrix = np.asarray(left_matrix, dtype=float)
        self.left_box = left_box

        extraction = np.asarray(audit.reduced_extraction(), dtype=float)
        embedding = np.asarray(audit.reduced_embedding("symmetric"), dtype=float)
        self.extraction_box = base.constant_matrix_box(
            extraction, exact_zero_one=True
        )
        self.embedding_box = base.constant_matrix_box(
            embedding, exact_zero_one=True
        )
        self._cache: dict[tuple[float, float], Any] = {}

        if self.knots.ndim != 1 or self.knots.size < 2:
            raise ValueError("Invalid spline knot vector")
        if not self.domain_left < self.domain_right:
            raise ValueError("Invalid generator-envelope domain")

        tolerance = 128.0 * np.finfo(float).eps * max(
            abs(self.domain_left), abs(self.domain_right), 1.0
        )
        if self.domain_left < self.knots[0] - tolerance:
            raise ValueError("Generator domain starts below spline domain")
        if self.domain_right > self.knots[-1] + tolerance:
            raise ValueError("Generator domain ends above spline domain")

    @property
    def cache_size(self) -> int:
        return len(self._cache)

    def point(self, value: float) -> np.ndarray:
        value = float(value)
        tolerance = 128.0 * np.finfo(float).eps * max(
            abs(self.domain_left), abs(self.domain_right), 1.0
        )
        if value < self.domain_left - tolerance or value > self.domain_right + tolerance:
            raise ValueError(f"Generator point {value:.17g} outside pilot domain")
        state = np.asarray(self.spline(value), dtype=float)
        raw = np.asarray(
            self.audit.reduced_jacobian_rotation(
                state, kappa0=self.kappa0, params=self.params
            ),
            dtype=float,
        )
        transformed = self.left_matrix @ raw @ self.basis
        if transformed.shape != (9, 9) or not np.all(np.isfinite(transformed)):
            raise FloatingPointError("Invalid point generator")
        return transformed

    def box(self, left: float, right: float) -> Any:
        left = float(left)
        right = float(right)
        if right < left:
            left, right = right, left

        tolerance = 128.0 * np.finfo(float).eps * max(
            abs(self.domain_left), abs(self.domain_right), abs(left), abs(right), 1.0
        )
        if left < self.domain_left - tolerance:
            raise ValueError("Generator interval below pilot domain")
        if right > self.domain_right + tolerance:
            raise ValueError("Generator interval above pilot domain")

        left = max(left, self.domain_left)
        right = min(right, self.domain_right)
        key = (left, right)
        cached = self._cache.get(key)
        if cached is not None:
            return cached

        first = max(
            0, int(np.searchsorted(self.knots, left, side="right") - 1)
        )
        last = min(
            self.knots.size - 2,
            int(np.searchsorted(self.knots, right, side="left")),
        )

        boxes: list[Any] = []
        for index in range(first, last + 1):
            knot_left = float(self.knots[index])
            knot_right = float(self.knots[index + 1])
            segment_left = max(left, knot_left)
            segment_right = min(right, knot_right)
            # A segment selected by searchsorted can be a floating-point
            # near-touch with no actual overlap.  The old tolerance test kept
            # such a segment when 0 < segment_left-segment_right <= tolerance,
            # which then produced dx_left > dx_right and an invalid Box.
            # If the floating endpoints are ordered as an empty intersection,
            # skip it unconditionally; any true knot contact is represented by
            # the adjacent segment with segment_left <= segment_right.
            if segment_right < segment_left:
                continue

            dx_left = max(0.0, segment_left - knot_left)
            dx_right = min(knot_right - knot_left, segment_right - knot_left)
            coefficients = np.asarray(self.spline.c[:, index, :], dtype=float)
            state_box = self.base.interval_cubic(
                coefficients, dx_left, dx_right
            )
            generator_box = self.base.reduced_rotation_generator_interval(
                state_box,
                kappa0=self.kappa0,
                params=self.params,
                extraction_box=self.extraction_box,
                embedding_box=self.embedding_box,
                left_box=self.left_box,
                basis_box=self.basis_box,
            )
            boxes.append(generator_box)

        if not boxes:
            raise RuntimeError(
                f"No spline segment overlaps [{left:.17g}, {right:.17g}]"
            )
        result = self.base.hull(boxes)
        self._cache[key] = result
        return result


def hermite_path_box(
    base: ModuleType,
    y0: np.ndarray,
    y1: np.ndarray,
    f0: np.ndarray,
    f1: np.ndarray,
    step: float,
    *,
    tau_left: float,
    tau_right: float,
) -> Any:
    a0 = y0
    a1 = step * f0
    a2 = -3.0 * y0 - 2.0 * step * f0 + 3.0 * y1 - step * f1
    a3 = 2.0 * y0 + step * f0 - 2.0 * y1 + step * f1
    tau = base.Box(np.asarray(float(tau_left)), np.asarray(float(tau_right)))
    return base.polynomial_box([a0, a1, a2, a3], tau)

def hermite_derivative_box(
    base: ModuleType,
    y0: np.ndarray,
    y1: np.ndarray,
    f0: np.ndarray,
    f1: np.ndarray,
    step: float,
    *,
    tau_left: float,
    tau_right: float,
) -> Any:
    a1 = step * f0
    a2 = -3.0 * y0 - 2.0 * step * f0 + 3.0 * y1 - step * f1
    a3 = 2.0 * y0 + step * f0 - 2.0 * y1 + step * f1
    tau = base.Box(np.asarray(float(tau_left)), np.asarray(float(tau_right)))
    derivative_tau = base.polynomial_box([a1, 2.0 * a2, 3.0 * a3], tau)
    return base.iscale(derivative_tau, 1.0 / step)


def hermite_derivative_value(
    y0: np.ndarray,
    y1: np.ndarray,
    f0: np.ndarray,
    f1: np.ndarray,
    step: float,
    tau: float,
) -> np.ndarray:
    a1 = step * f0
    a2 = -3.0 * y0 - 2.0 * step * f0 + 3.0 * y1 - step * f1
    a3 = 2.0 * y0 + step * f0 - 2.0 * y1 + step * f1
    return (a1 + 2.0 * a2 * tau + 3.0 * a3 * tau * tau) / step


def centered_hermite_residual_box(
    base: ModuleType,
    y0: np.ndarray,
    y1: np.ndarray,
    f0: np.ndarray,
    f1: np.ndarray,
    step: float,
    generator_box: Any,
    generator_midpoint: np.ndarray,
    path_box: Any,
    *,
    tau_left: float,
    tau_right: float,
) -> Any:
    """Cancellation-preserving enclosure of U' - B U.

    Freeze B at the microinterval midpoint B_c.  Because U is cubic Hermite,
    U' - B_c U is a cubic matrix polynomial whose coefficients can be formed
    before interval evaluation.  The remaining generator variation enters as

        -(B-B_c) U,

    and is small on the exact microinterval.
    """
    a0 = y0
    a1 = step * f0
    a2 = -3.0 * y0 - 2.0 * step * f0 + 3.0 * y1 - step * f1
    a3 = 2.0 * y0 + step * f0 - 2.0 * y1 + step * f1

    residual_coefficients = [
        a1 / step - generator_midpoint @ a0,
        2.0 * a2 / step - generator_midpoint @ a1,
        3.0 * a3 / step - generator_midpoint @ a2,
        -generator_midpoint @ a3,
    ]
    tau = base.Box(np.asarray(float(tau_left)), np.asarray(float(tau_right)))
    frozen_residual = base.polynomial_box(residual_coefficients, tau)
    generator_variation = base.isub(
        generator_box, base.exact_box(generator_midpoint)
    )
    return base.isub(
        frozen_residual,
        base.imatmul(generator_variation, path_box),
    )


def hermite_path_value(
    y0: np.ndarray,
    y1: np.ndarray,
    f0: np.ndarray,
    f1: np.ndarray,
    step: float,
    tau: float,
) -> np.ndarray:
    a0 = y0
    a1 = step * f0
    a2 = -3.0 * y0 - 2.0 * step * f0 + 3.0 * y1 - step * f1
    a3 = 2.0 * y0 + step * f0 - 2.0 * y1 + step * f1
    return ((a3 * tau + a2) * tau + a1) * tau + a0


def inverse_path_upper(
    base: ModuleType,
    path_box: Any,
    path_midpoint: np.ndarray,
) -> tuple[float, float]:
    """Banach-lemma bound for every U in path_box.

    With a numerical approximate inverse V of the midpoint path,

        ||I - V U||_2 <= eta < 1

    implies

        ||U^{-1}||_2 <= ||V||_2 / (1-eta).

    All products involving the varying U are evaluated with outward-rounded
    interval arithmetic.
    """
    approximate_inverse = np.linalg.inv(path_midpoint)
    inverse_box = base.float_box(approximate_inverse, ulps=6)
    product_box = base.imatmul(inverse_box, path_box)
    identity_box = base.constant_matrix_box(np.eye(9), exact_zero_one=True)
    residual_box = base.isub(product_box, identity_box)
    eta = box_spectral_upper(base, residual_box)
    if not eta < 1.0:
        raise FloatingPointError(
            f"Banach inverse failed: ||I-VU||_2 <= {eta:.6e}"
        )
    inverse_norm = box_spectral_upper(base, inverse_box)
    return outward(inverse_norm / (1.0 - eta)), eta


def validate_transport_relative_defect(
    base: ModuleType,
    envelope: LocalCubicGeneratorEnvelope,
    *,
    start: float,
    step: float,
    steps: int,
    residual_subdivisions: int,
    label: str,
) -> LocalValidatedTransport:
    if steps < 1:
        raise ValueError("steps must be positive")
    if residual_subdivisions < 1:
        raise ValueError("residual_subdivisions must be positive")

    center = np.eye(9, dtype=float)
    relative_error = 0.0

    maximum_microbox_width = 0.0
    maximum_path_inverse_test = 0.0
    maximum_defect_rate = 0.0
    accumulated_defect = 0.0
    maximum_local_relative = 0.0
    maximum_local_absolute = 0.0

    progress_every = max(1, steps // 10)
    for index in range(steps):
        s0 = start + index * step
        sm = s0 + 0.5 * step
        s1 = s0 + step
        b0 = envelope.point(s0)
        bm = envelope.point(sm)
        b1 = envelope.point(s1)

        y0 = center
        k1 = b0 @ y0
        k2 = bm @ (y0 + 0.5 * step * k1)
        k3 = bm @ (y0 + 0.5 * step * k2)
        k4 = b1 @ (y0 + step * k3)
        y1 = y0 + (step / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        f0 = b0 @ y0
        f1 = b1 @ y1

        local_integral = 0.0
        for subdivision in range(residual_subdivisions):
            tau_left = subdivision / residual_subdivisions
            tau_right = (subdivision + 1) / residual_subdivisions
            tau_middle = 0.5 * (tau_left + tau_right)
            sub_left = s0 + tau_left * step
            sub_right = s0 + tau_right * step

            generator_box = envelope.box(sub_left, sub_right)
            path_box = hermite_path_box(
                base,
                y0,
                y1,
                f0,
                f1,
                step,
                tau_left=tau_left,
                tau_right=tau_right,
            )
            path_midpoint = hermite_path_value(
                y0, y1, f0, f1, step, tau_middle
            )
            generator_midpoint = envelope.point(s0 + tau_middle * step)
            residual_box = centered_hermite_residual_box(
                base,
                y0,
                y1,
                f0,
                f1,
                step,
                generator_box,
                generator_midpoint,
                path_box,
                tau_left=tau_left,
                tau_right=tau_right,
            )

            inverse_upper, inverse_test = inverse_path_upper(
                base, path_box, path_midpoint
            )
            residual_upper = base.box_frobenius_upper(residual_box)
            defect_rate = outward(inverse_upper * residual_upper)
            substep = step * (tau_right - tau_left)
            local_integral = outward(local_integral + defect_rate * substep)

            maximum_microbox_width = max(
                maximum_microbox_width, box_width_max(generator_box)
            )
            maximum_path_inverse_test = max(
                maximum_path_inverse_test, inverse_test
            )
            maximum_defect_rate = max(maximum_defect_rate, defect_rate)

        with mp.workdps(base.MP_DPS):
            growth = mp.exp(mp.mpf(local_integral))
            next_relative = growth * (1 + mp.mpf(relative_error)) - 1
            local_relative = mp.expm1(mp.mpf(local_integral))
            _, next_high = base.mp_bracket(next_relative, ulps=4)
            _, local_high = base.mp_bracket(local_relative, ulps=4)
        relative_error = float(next_high)
        local_relative_float = float(local_high)
        center = y1

        center_norm = box_spectral_upper(base, base.float_box(center, ulps=6))
        local_absolute = outward(center_norm * local_relative_float)
        accumulated_defect = outward(accumulated_defect + local_integral)
        maximum_local_relative = max(
            maximum_local_relative, local_relative_float
        )
        maximum_local_absolute = max(maximum_local_absolute, local_absolute)

        if index == 0 or index + 1 == steps or (index + 1) % progress_every == 0:
            current_radius = outward(center_norm * relative_error)
            print(
                f"    {label}: [{index + 1:>5}/{steps}] "
                f"radius={current_radius:.3e} microboxes={int(getattr(envelope, "cache_size", 0))}",
                flush=True,
            )

    final_norm = box_spectral_upper(base, base.float_box(center, ulps=6))
    radius = outward(final_norm * relative_error)
    return LocalValidatedTransport(
        center=center,
        radius=radius,
        steps=steps,
        residual_subdivisions=residual_subdivisions,
        maximum_microbox_width=maximum_microbox_width,
        maximum_path_distance_from_identity=maximum_path_inverse_test,
        maximum_relative_defect_rate=maximum_defect_rate,
        accumulated_relative_defect=accumulated_defect,
        maximum_local_relative_error=maximum_local_relative,
        maximum_local_absolute_radius=maximum_local_absolute,
        microbox_cache_size=int(getattr(envelope, "cache_size", 0)),
    )

def relative_matrix_difference(a: np.ndarray, b: np.ndarray) -> float:
    denominator = max(
        float(np.linalg.norm(a, ord="fro")),
        float(np.linalg.norm(b, ord="fro")),
        1e-300,
    )
    return float(np.linalg.norm(a - b, ord="fro") / denominator)


