def run_self_test(base: ModuleType) -> None:
    rng = np.random.default_rng(20260806)
    raw = rng.normal(size=(9, 9))
    skew = 20.0 * (raw - raw.T) / max(np.linalg.norm(raw - raw.T, ord=2), 1e-15)
    generator = skew - 0.03 * np.eye(9)

    class ConstantEnvelope:
        def __init__(self) -> None:
            self.cache: dict[Any, Any] = {}

        def point(self, value: float) -> np.ndarray:
            del value
            return generator

        def box(self, left: float, right: float) -> Any:
            key = (float(left).hex(), float(right).hex())
            if key not in self.cache:
                self.cache[key] = base.float_box(generator, ulps=4)
            return self.cache[key]

    length = 0.37
    steps = 240
    result = validate_transport_relative_defect(
        base,
        ConstantEnvelope(),
        start=0.0,
        step=length / steps,
        steps=steps,
        residual_subdivisions=4,
        label="self-test",
    )
    exact = base.expm(generator * length)
    actual = float(np.linalg.norm(result.center - exact, ord="fro"))
    if actual > result.radius:
        raise AssertionError(
            f"relative-defect self-test escaped enclosure: {actual:.3e} > {result.radius:.3e}"
        )
    print(
        "relative-defect self-test passed: "
        f"actual={actual:.3e}, radius={result.radius:.3e}, "
        f"max inverse residual={result.maximum_path_distance_from_identity:.3e}",
        flush=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Pilot exact micro-spline boxes and moving-frame relative-defect validation at one Q=550 dense start."
    )
    parser.add_argument("--base-script", type=Path, default=DEFAULT_BASE)
    parser.add_argument("--dense-raw", type=Path, default=DEFAULT_DENSE_RAW)
    parser.add_argument("--audit-script", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--orbit", type=Path, default=DEFAULT_ORBIT)
    parser.add_argument("--q", type=float, default=550.0)
    parser.add_argument("--center-index", type=int, default=67)
    parser.add_argument("--steps-per-line", type=int, default=656)
    parser.add_argument("--residual-subdivisions", type=int, default=4)
    parser.add_argument("--gamma-rho", type=float, default=0.3)
    parser.add_argument("--tail-periods", type=int, default=70)
    parser.add_argument("--steps-per-period", type=int, default=160)
    parser.add_argument("--samples-per-rotation", type=int, default=720)
    parser.add_argument("--initial-x-perturbation", type=float, default=1e-6)
    parser.add_argument("--mp-dps", type=int, default=80)
    parser.add_argument("--planar-failure-threshold", type=float, default=0.95)
    parser.add_argument("--target-radius", type=float, default=3e-3)
    parser.add_argument("--output-prefix", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.steps_per_line < 20:
        parser.error("--steps-per-line must be at least 20")
    if args.residual_subdivisions < 1:
        parser.error("--residual-subdivisions must be positive")
    if args.mp_dps < 50:
        parser.error("--mp-dps must be at least 50")
    if not (0.0 < args.planar_failure_threshold < 1.0):
        parser.error("--planar-failure-threshold must lie in (0,1)")

    base = load_module(args.base_script, "relative_defect_microbox_base")
    base.MP_DPS = int(args.mp_dps)
    require_attributes(
        base,
        (
            "Box",
            "float_box",
            "exact_box",
            "constant_matrix_box",
            "interval_cubic",
            "reduced_rotation_generator_interval",
            "polynomial_box",
            "hermite_residual_box",
            "box_abs_upper",
            "box_frobenius_upper",
            "imatmul",
            "isub",
            "iadd",
            "iscale",
            "hull",
            "mp_bracket",
            "mp_inverse_enclosure",
            "structural_bounds",
            "expm",
        ),
        "base interval script",
    )

    if args.self_test:
        run_self_test(base)
        return

    for path, label in (
        (args.dense_raw, "dense raw"),
        (args.audit_script, "audit script"),
        (args.orbit, "orbit cache"),
    ):
        if not path.exists():
            parser.error(f"{label} not found: {path}")

    audit = load_module(args.audit_script, "relative_defect_microbox_audit")
    require_attributes(
        audit,
        (
            "ModelParameters",
            "load_orbit",
            "collect_uniform_tail",
            "build_state_spline",
            "reduced_jacobian_rotation",
            "reduced_extraction",
            "reduced_embedding",
            "full_jacobian",
        ),
        "audit script",
    )

    with np.load(args.dense_raw, allow_pickle=True) as raw:
        q_stored = float(raw["q"])
        if not math.isclose(q_stored, args.q, rel_tol=0.0, abs_tol=1e-10):
            raise ValueError(f"Dense raw Q={q_stored:g}, requested Q={args.q:g}")
        starts = np.asarray(raw["starts"], dtype=float)
        if not (0 <= args.center_index < starts.size):
            parser.error(f"--center-index must lie in [0,{starts.size - 1}]")
        p_line = float(raw["p_line"])
        p_oriented = float(raw["p_oriented"])
        basis = np.asarray(raw["basis"], dtype=float)
        labels = [str(value) for value in raw["basis_labels"]]
        archived = {
            "line": np.asarray(raw["fine_line"], dtype=float)[args.center_index],
            "second": np.asarray(raw["fine_second"], dtype=float)[args.center_index],
            "oriented": np.asarray(raw["fine_oriented"], dtype=float)[args.center_index],
            "two_line": np.asarray(raw["fine_two_line"], dtype=float)[args.center_index],
        }

    if labels[:2] != ["lower angular bascule", "upper counterbalance"]:
        raise RuntimeError("Unexpected active basis ordering")
    if "upper z residual" not in labels:
        raise RuntimeError("upper z residual basis label missing")
    z_index = labels.index("upper z residual")

    start = float(starts[args.center_index])
    second_length = p_oriented - p_line
    common_step = p_line / args.steps_per_line
    lengths = {
        "line": p_line,
        "second": second_length,
        "oriented": p_oriented,
        "two_line": 2.0 * p_line,
    }
    step_counts = {name: int(round(length / common_step)) for name, length in lengths.items()}
    for name, length in lengths.items():
        represented = step_counts[name] * common_step
        tolerance = 128.0 * np.finfo(float).eps * max(abs(length), 1.0)
        if abs(represented - length) > tolerance:
            raise RuntimeError(
                f"Common step does not represent {name} exactly enough: "
                f"{represented:.17g} vs {length:.17g}. Choose another --steps-per-line."
            )

    print(f"Script version       = {SCRIPT_VERSION}")
    print(f"selected center      = {args.center_index}/{starts.size - 1}")
    print(f"selected start       = {start:.15f}")
    print(f"steps per P_line     = {args.steps_per_line}")
    print(f"common step          = {common_step:.15e}")
    print(f"step counts          = {step_counts}")
    print(f"residual subdivisions= {args.residual_subdivisions}")
    print(f"mp.dps               = {args.mp_dps}")

    params = audit.ModelParameters(gamma_rho=args.gamma_rho)
    orbit = audit.load_orbit(args.q, args.orbit)
    tail = audit.collect_uniform_tail(
        orbit,
        tail_periods=args.tail_periods,
        steps_per_period=args.steps_per_period,
        samples_per_rotation=args.samples_per_rotation,
        initial_x_perturbation=args.initial_x_perturbation,
        params=params,
        progress_every=100,
    )
    spline = audit.build_state_spline(tail)
    metric = np.asarray(tail.metric, dtype=float)
    gram_error = float(np.linalg.norm(basis.T @ metric @ basis - np.eye(9), ord="fro"))

    inverse, inverse_box = base.mp_inverse_enclosure(basis)
    basis_box = base.constant_matrix_box(basis)
    inverse_identity_error = float(np.linalg.norm(inverse @ basis - np.eye(9), ord="fro"))

    domain_left = start
    domain_right = start + max(lengths.values())
    kappa0 = (55.0 / 6.0) * (10.0 / args.q)
    envelope = LocalCubicGeneratorEnvelope(
        base,
        audit,
        spline,
        np.asarray(tail.s, dtype=float),
        domain_left=domain_left,
        domain_right=domain_right,
        kappa0=kappa0,
        params=params,
        basis=basis,
        basis_box=basis_box,
        left_matrix=inverse,
        left_box=inverse_box,
    )

    # Point containment checks on the exact local boxes.
    point_containment = True
    point_width_maximum = 0.0
    for value in np.linspace(domain_left, domain_right, 17):
        point = envelope.point(float(value))
        box = envelope.box(float(value), float(value))
        point_containment = point_containment and base.box_contains(box, point)
        point_width_maximum = max(point_width_maximum, box_width_max(box))
    if not point_containment:
        raise AssertionError("Point generator escaped exact micro-box enclosure")

    transports: dict[str, LocalValidatedTransport] = {}
    transport_starts = {
        "line": start,
        "second": start + p_line,
        "oriented": start,
        "two_line": start,
    }
    for name in ("line", "second", "oriented", "two_line"):
        print(f"  validating {name}", flush=True)
        transports[name] = validate_transport_relative_defect(
            base,
            envelope,
            start=transport_starts[name],
            step=common_step,
            steps=step_counts[name],
            residual_subdivisions=args.residual_subdivisions,
            label=name,
        )
        print(
            f"  {name} done: radius={transports[name].radius:.6e}, "
            f"archived discrepancy={relative_matrix_difference(transports[name].center, archived[name]):.3e}",
            flush=True,
        )

    structural = base.structural_bounds(
        transports["line"].center,
        transports["line"].radius,
        transports["second"].center,
        transports["second"].radius,
        transports["oriented"].center,
        transports["oriented"].radius,
        transports["two_line"].center,
        transports["two_line"].radius,
        z_index=z_index,
        tau=args.planar_failure_threshold,
    )

    rows: dict[str, Any] = {}
    for name, result in transports.items():
        rows[name] = {
            "steps": result.steps,
            "radius": result.radius,
            "archived_relative_discrepancy": relative_matrix_difference(
                result.center, archived[name]
            ),
            "maximum_microbox_width": result.maximum_microbox_width,
            "maximum_path_distance_from_identity": result.maximum_path_distance_from_identity,
            "maximum_relative_defect_rate": result.maximum_relative_defect_rate,
            "accumulated_relative_defect": result.accumulated_relative_defect,
            "maximum_local_relative_error": result.maximum_local_relative_error,
            "maximum_local_absolute_radius": result.maximum_local_absolute_radius,
            "microbox_cache_size": result.microbox_cache_size,
        }

    endpoint_radius_sum = transports["oriented"].radius + transports["two_line"].radius
    pilot_target_passed = bool(
        transports["oriented"].radius <= args.target_radius
        and transports["two_line"].radius <= args.target_radius
        and structural["all_structural_pass"]
    )
    if pilot_target_passed:
        classification = (
            "RELATIVE-DEFECT MICRO-BOX PILOT PASSED: at the selected start, the "
            "moving-frame validation preserves all four structural statements "
            "with both long-endpoint radii below the requested target."
        )
    elif structural["all_structural_pass"]:
        classification = (
            "STRUCTURAL PILOT PASSED, TARGET RADIUS NOT YET MET: the selected "
            "start is rigorously separated, but refinement is still useful before "
            "scaling to all dense starts."
        )
    else:
        classification = (
            "PILOT OPEN: exact micro-boxes and relative-defect validation improved "
            "the architecture but do not yet preserve every structural margin at "
            "the selected start."
        )

    payload: dict[str, Any] = {
        "script_version": SCRIPT_VERSION,
        "scope": "one-start validated frozen cubic-spline linear cocycle; nonlinear orbit cache not yet validated",
        "dense_raw": str(args.dense_raw),
        "dense_raw_sha256": sha256(args.dense_raw),
        "orbit": str(args.orbit),
        "orbit_sha256": sha256(args.orbit),
        "q": args.q,
        "center_index": args.center_index,
        "start": start,
        "p_line": p_line,
        "p_oriented": p_oriented,
        "common_step": common_step,
        "steps_per_line": args.steps_per_line,
        "step_counts": step_counts,
        "residual_subdivisions": args.residual_subdivisions,
        "mp_dps": args.mp_dps,
        "basis_gram_error": gram_error,
        "basis_inverse_identity_error": inverse_identity_error,
        "point_generator_containment_passed": point_containment,
        "point_generator_interval_width_maximum": point_width_maximum,
        "target_radius": args.target_radius,
        "endpoint_radius_sum": endpoint_radius_sum,
        "transports": rows,
        "structural": {
            key: (bool(value) if isinstance(value, (bool, np.bool_)) else float(value))
            for key, value in structural.items()
        },
        "pilot_target_passed": pilot_target_passed,
        "classification": classification,
    }

    prefix = args.output_prefix
    prefix.parent.mkdir(parents=True, exist_ok=True)
    report_path = prefix.with_name(prefix.name + "_report.txt")
    json_path = prefix.with_suffix(".json")
    raw_path = prefix.with_name(prefix.name + "_raw.npz")
    write_report(report_path, payload)
    json_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    np.savez_compressed(
        raw_path,
        script_version=np.asarray(SCRIPT_VERSION),
        center_index=np.asarray(args.center_index),
        start=np.asarray(start),
        p_line=np.asarray(p_line),
        p_oriented=np.asarray(p_oriented),
        common_step=np.asarray(common_step),
        basis=basis,
        basis_labels=np.asarray(labels, dtype=object),
        line_center=transports["line"].center,
        line_radius=np.asarray(transports["line"].radius),
        second_center=transports["second"].center,
        second_radius=np.asarray(transports["second"].radius),
        oriented_center=transports["oriented"].center,
        oriented_radius=np.asarray(transports["oriented"].radius),
        two_line_center=transports["two_line"].center,
        two_line_radius=np.asarray(transports["two_line"].radius),
    )

    print("=" * 78)
    print(report_path.read_text(), end="")
    print(f"report = {report_path.resolve()}")
    print(f"JSON   = {json_path.resolve()}")
    print(f"raw    = {raw_path.resolve()}")


if __name__ == "__main__":
    main()
